#!/usr/bin/env node
/**
 * Generate resources/company.json from environment variables.
 *
 * This is used when packaging the Allternit Platform app so that company
 * standards (auth, endpoints, encryption) are baked into every build and users
 * do not have to touch env vars on each host computer.
 *
 * Required / commonly set env vars:
 *   ALLTERNIT_TENANT_ID              - tenant marker (default: allternit-default)
 *   ALLTERNIT_GATEWAY_URL            - API gateway URL (default: http://localhost:8013)
 *   ALLTERNIT_TERMINAL_SERVER_URL    - Gizzi runtime URL (default: http://127.0.0.1:4096)
 *   ALLTERNIT_RAILS_URL              - Rails service URL (default: http://127.0.0.1:8080)
 *   ALLTERNIT_RAILS_WORKSPACE_ID     - Rails workspace ID (default: default)
 *   ALLTERNIT_CRON_DAEMON_URL        - Cron daemon URL (default: http://127.0.0.1:4096/cron)
 *   ALLTERNIT_VM_DIR                 - VM storage directory (optional)
 *   ALLTERNIT_SELF_HOSTED            - Self-hosted mode, skips Clerk (default: false)
 *   NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY - Clerk publishable key (optional)
 *   CLERK_JWKS_URL                   - Clerk JWKS URL (optional)
 *   CLERK_ISSUER                     - Clerk JWT issuer (optional)
 *   CLERK_WEBHOOK_SECRET             - Clerk webhook secret (optional)
 *   ALLTERNIT_ENCRYPTION_KEY         - Local encryption key (optional, generated if empty)
 *
 * Usage:
 *   node scripts/generate-company-config.cjs
 *   node scripts/generate-company-config.cjs --out ./dist/company.json
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

function generateKey() {
  return crypto.randomBytes(32).toString('hex');
}

function getEnv(name, fallback = '') {
  const value = process.env[name];
  return value !== undefined && value.trim().length > 0 ? value.trim() : fallback;
}

function main() {
  const args = process.argv.slice(2);
  const outArg = args.find((a) => a.startsWith('--out='));
  const outPath = outArg
    ? path.resolve(outArg.split('=')[1])
    : path.resolve(__dirname, '..', 'resources', 'company.json');

  const encryptionKey = getEnv('ALLTERNIT_ENCRYPTION_KEY') || generateKey();

  const config = {
    $schema: 'https://allternit.io/schemas/company-config.json',
    _comment:
      'Company-level configuration baked into packaged Allternit Platform apps. Generated by scripts/generate-company-config.cjs.',
    tenantId: getEnv('ALLTERNIT_TENANT_ID', 'allternit-default'),
    gatewayUrl: getEnv('ALLTERNIT_GATEWAY_URL', 'http://localhost:8013'),
    terminalServerUrl: getEnv('ALLTERNIT_TERMINAL_SERVER_URL', 'http://127.0.0.1:4096'),
    railsUrl: getEnv('ALLTERNIT_RAILS_URL', 'http://127.0.0.1:8080'),
    railsWorkspaceId: getEnv('ALLTERNIT_RAILS_WORKSPACE_ID', 'default'),
    cronDaemonUrl: getEnv('ALLTERNIT_CRON_DAEMON_URL', 'http://127.0.0.1:4096/cron'),
    vmDir: getEnv('ALLTERNIT_VM_DIR', ''),
    clerkPublishableKey: getEnv('NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY', ''),
    clerkJwksUrl: getEnv('CLERK_JWKS_URL', ''),
    clerkIssuer: getEnv('CLERK_ISSUER', ''),
    clerkWebhookSecret: getEnv('CLERK_WEBHOOK_SECRET', ''),
    selfHosted: getEnv('ALLTERNIT_SELF_HOSTED', 'false').toLowerCase() === 'true',
    encryptionKey,
  };

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, JSON.stringify(config, null, 2) + '\n', 'utf8');

  const usingGeneratedKey = !process.env.ALLTERNIT_ENCRYPTION_KEY;
  console.log(`Wrote company config to ${outPath}`);
  if (usingGeneratedKey) {
    console.log('Generated a new encryption key. Save ALLTERNIT_ENCRYPTION_KEY if you want deterministic builds.');
  }
  if (!config.clerkPublishableKey && !config.selfHosted) {
    console.log('No Clerk publishable key set and selfHosted is false. Set ALLTERNIT_SELF_HOSTED=true for packaged apps without Clerk.');
  }
  if (config.selfHosted) {
    console.log('Self-hosted mode enabled. Clerk JWT verification will be skipped.');
  }
}

main();
