#!/usr/bin/env node
import { chmod, mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { homedir, platform } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const HOST_NAME = 'com.allternit.desktop';
export const HOST_DESCRIPTION =
  'Allternit Desktop Native Messaging Host — bridges Allternit browser mode/debug extension to Allternit Desktop';

const __filename = fileURLToPath(import.meta.url);
const SCRIPT_DIR = dirname(__filename);
const PACKAGE_DIR = resolve(SCRIPT_DIR, '..');

export function normalizeExtensionOrigin(value) {
  if (!value || typeof value !== 'string') return null;
  const trimmed = value.trim();
  if (!trimmed) return null;
  if (/^chrome-extension:\/\/[a-p]{32}\/$/.test(trimmed)) return trimmed;
  if (/^[a-p]{32}$/.test(trimmed)) return `chrome-extension://${trimmed}/`;
  throw new Error(
    `Invalid extension origin/id: ${value}. Expected a 32-character Chrome extension id or chrome-extension://<id>/`,
  );
}

export function parseAllowedOrigins(values = [], env = process.env) {
  const explicit = values
    .flatMap((value) => String(value).split(','))
    .map(normalizeExtensionOrigin)
    .filter(Boolean);

  const envValues = [
    env.ALLTERNIT_EXTENSION_ID,
    env.ALLTERNIT_EXTENSION_IDS,
    env.ALLTERNIT_EXTENSION_ORIGIN,
    env.ALLTERNIT_EXTENSION_ORIGINS,
  ]
    .filter(Boolean)
    .flatMap((value) => String(value).split(','))
    .map(normalizeExtensionOrigin)
    .filter(Boolean);

  return Array.from(new Set([...explicit, ...envValues]));
}

export function getNativeMessagingDirs(targetPlatform = platform(), home = homedir()) {
  if (targetPlatform === 'darwin') {
    return [
      ['Google Chrome', join(home, 'Library', 'Application Support', 'Google', 'Chrome', 'NativeMessagingHosts')],
      [
        'Google Chrome for Testing',
        join(home, 'Library', 'Application Support', 'Google', 'ChromeForTesting', 'NativeMessagingHosts'),
      ],
      ['Microsoft Edge', join(home, 'Library', 'Application Support', 'Microsoft Edge', 'NativeMessagingHosts')],
      ['Brave', join(home, 'Library', 'Application Support', 'BraveSoftware', 'Brave-Browser', 'NativeMessagingHosts')],
      ['Chromium', join(home, 'Library', 'Application Support', 'Chromium', 'NativeMessagingHosts')],
      ['Arc', join(home, 'Library', 'Application Support', 'Arc', 'User Data', 'NativeMessagingHosts')],
    ];
  }

  if (targetPlatform === 'linux') {
    return [
      ['Google Chrome', join(home, '.config', 'google-chrome', 'NativeMessagingHosts')],
      ['Google Chrome for Testing', join(home, '.config', 'google-chrome-for-testing', 'NativeMessagingHosts')],
      ['Microsoft Edge', join(home, '.config', 'microsoft-edge', 'NativeMessagingHosts')],
      ['Brave', join(home, '.config', 'BraveSoftware', 'Brave-Browser', 'NativeMessagingHosts')],
      ['Chromium', join(home, '.config', 'chromium', 'NativeMessagingHosts')],
    ];
  }

  if (targetPlatform === 'win32') {
    const appData = process.env.APPDATA || join(home, 'AppData', 'Roaming');
    return [['Chromium browsers', join(appData, 'Allternit', 'NativeMessagingHosts')]];
  }

  return [];
}

export async function defaultHostCommand(packageDir = PACKAGE_DIR) {
  const binaryPath = join(packageDir, 'dist', 'native-host');
  if (await exists(binaryPath)) return `"${binaryPath}"`;

  const sourcePath = join(packageDir, 'native-host.ts');
  if (await commandExists('bun')) return `bun run "${sourcePath}"`;
  return `node --loader ts-node/esm "${sourcePath}"`;
}

export function wrapperPathFor(packageDir = PACKAGE_DIR, targetPlatform = platform()) {
  const extension = targetPlatform === 'win32' ? '.cmd' : '';
  return join(packageDir, 'dist', `allternit-native-host-wrapper${extension}`);
}

export async function createWrapperScript({
  command,
  packageDir = PACKAGE_DIR,
  targetPlatform = platform(),
  dryRun = false,
} = {}) {
  const wrapperPath = wrapperPathFor(packageDir, targetPlatform);
  const resolvedCommand = command || (await defaultHostCommand(packageDir));
  const content =
    targetPlatform === 'win32'
      ? `@echo off\r\nREM Generated by Allternit native host installer. Do not edit manually.\r\n${resolvedCommand} %*\r\n`
      : `#!/bin/sh\n# Generated by Allternit native host installer. Do not edit manually.\nexec ${resolvedCommand} "$@"\n`;

  if (!dryRun) {
    await mkdir(dirname(wrapperPath), { recursive: true });
    const existing = await readFile(wrapperPath, 'utf8').catch(() => null);
    if (existing !== content) {
      await writeFile(wrapperPath, content);
      if (targetPlatform !== 'win32') await chmod(wrapperPath, 0o755);
    }
  }

  return { wrapperPath, command: resolvedCommand, content };
}

export function createManifest({ wrapperPath, allowedOrigins }) {
  if (!Array.isArray(allowedOrigins) || allowedOrigins.length === 0) {
    throw new Error(
      'At least one concrete extension origin is required. Set ALLTERNIT_EXTENSION_ID or pass --extension-id <id>.',
    );
  }

  return {
    name: HOST_NAME,
    description: HOST_DESCRIPTION,
    path: wrapperPath,
    type: 'stdio',
    allowed_origins: allowedOrigins,
  };
}

export async function installNativeHost({
  allowedOrigins,
  command,
  dryRun = false,
  includeDefaultBrowsers = true,
  packageDir = PACKAGE_DIR,
  profileDirs = [],
  targetPlatform = platform(),
  home = homedir(),
} = {}) {
  const dirs = [
    ...(includeDefaultBrowsers ? getNativeMessagingDirs(targetPlatform, home) : []),
    ...profileDirs.map((profileDir) => [
      `Browser profile: ${profileDir}`,
      join(resolve(profileDir), 'NativeMessagingHosts'),
    ]),
  ];
  if (dirs.length === 0) {
    throw new Error(`Unsupported platform for native messaging host install: ${targetPlatform}`);
  }

  const wrapper = await createWrapperScript({ command, packageDir, targetPlatform, dryRun });
  const manifest = createManifest({ wrapperPath: wrapper.wrapperPath, allowedOrigins });
  const manifestContent = `${JSON.stringify(manifest, null, 2)}\n`;
  const writes = dirs.map(([browser, dir]) => ({
    browser,
    dir,
    manifestPath: join(dir, `${HOST_NAME}.json`),
  }));

  if (!dryRun) {
    for (const write of writes) {
      await mkdir(write.dir, { recursive: true });
      const existing = await readFile(write.manifestPath, 'utf8').catch(() => null);
      if (existing !== manifestContent) {
        await writeFile(write.manifestPath, manifestContent);
      }
    }
  }

  return { wrapper, manifest, writes, dryRun };
}

async function exists(path) {
  return stat(path)
    .then(() => true)
    .catch(() => false);
}

async function commandExists(command) {
  const pathDirs = String(process.env.PATH || '').split(':').filter(Boolean);
  for (const pathDir of pathDirs) {
    if (await exists(join(pathDir, command))) return true;
  }
  return false;
}

function parseArgs(argv) {
  const options = {
    allowedOriginInputs: [],
    profileDirs: [],
    dryRun: false,
    includeDefaultBrowsers: true,
    uninstall: false,
    command: undefined,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--') {
      continue;
    } else if (arg === '--dry-run' || arg === '--doctor') {
      options.dryRun = true;
    } else if (arg === '--uninstall') {
      options.uninstall = true;
    } else if (arg === '--extension-id' || arg === '--extension-origin') {
      const value = argv[index + 1];
      if (!value) throw new Error(`${arg} requires a value`);
      options.allowedOriginInputs.push(value);
      index += 1;
    } else if (arg === '--host-command') {
      const value = argv[index + 1];
      if (!value) throw new Error('--host-command requires a value');
      options.command = value;
      index += 1;
    } else if (arg === '--profile-dir') {
      const value = argv[index + 1];
      if (!value) throw new Error('--profile-dir requires a value');
      options.profileDirs.push(value);
      index += 1;
    } else if (arg === '--profile-only') {
      options.includeDefaultBrowsers = false;
    } else if (arg === '--help' || arg === '-h') {
      options.help = true;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return options;
}

async function uninstallNativeHost({ targetPlatform = platform(), home = homedir(), dryRun = false } = {}) {
  const writes = getNativeMessagingDirs(targetPlatform, home).map(([browser, dir]) => ({
    browser,
    manifestPath: join(dir, `${HOST_NAME}.json`),
  }));

  if (!dryRun) {
    const { rm } = await import('node:fs/promises');
    for (const write of writes) await rm(write.manifestPath, { force: true });
  }

  return writes;
}

function usage() {
  return `Usage:
  node scripts/native-host-installer.mjs --extension-id <chrome-extension-id>
  node scripts/native-host-installer.mjs --extension-origin chrome-extension://<id>/
  node scripts/native-host-installer.mjs --extension-id <id> --profile-dir <browser-user-data-dir>
  node scripts/native-host-installer.mjs --extension-id <id> --profile-dir <dir> --profile-only
  node scripts/native-host-installer.mjs --doctor --extension-id <id>
  node scripts/native-host-installer.mjs --uninstall

Environment:
  ALLTERNIT_EXTENSION_ID / ALLTERNIT_EXTENSION_IDS
  ALLTERNIT_EXTENSION_ORIGIN / ALLTERNIT_EXTENSION_ORIGINS
`;
}

if (process.argv[1] === __filename) {
  try {
    const args = parseArgs(process.argv.slice(2));
    if (args.help) {
      console.log(usage());
      process.exit(0);
    }

    if (args.uninstall) {
      const writes = await uninstallNativeHost({ dryRun: args.dryRun });
      console.log(JSON.stringify({ ok: true, action: 'uninstall', writes, dryRun: args.dryRun }, null, 2));
      process.exit(0);
    }

    const allowedOrigins = parseAllowedOrigins(args.allowedOriginInputs);
    const result = await installNativeHost({
      allowedOrigins,
      command: args.command,
      includeDefaultBrowsers: args.includeDefaultBrowsers,
      profileDirs: args.profileDirs,
      dryRun: args.dryRun,
    });
    console.log(JSON.stringify({ ok: true, ...result }, null, 2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    console.error(usage());
    process.exit(1);
  }
}
